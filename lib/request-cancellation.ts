import { activityMessage } from './activity-events.ts';
import { isDemoAdministrator } from './demo-permissions.ts';
import type { InternalUser, ServiceRequest } from './service-requests';
import { canPerformAssessmentRole } from './assessment-routing.ts';
import { routingUsers } from './assessment-routing-schema.ts';
import { appendActivity, type OperationActor } from './request-operations.ts';

export function canCancelRequest(record: ServiceRequest, actor: OperationActor | undefined, users: InternalUser[]): boolean {
  return ['待评估', '待确认', '待受理'].includes(record.status)
    && !!record.operations?.assessment?.managerId
    && canPerformAssessmentRole(record, actor, 'manager', users)
    && (isDemoAdministrator(actor, users) || routingUsers(users, 'manager').some(user => user.id === actor?.id));
}

export function cancelRequest(record: ServiceRequest, actor: OperationActor, users: InternalUser[], reason: string, now = new Date().toISOString()): ServiceRequest {
  if (!canCancelRequest(record, actor, users)) throw new Error('仅负责项目经理可取消待评估、待确认或待受理的服务请求。');
  if (!reason.trim()) throw new Error('请填写取消原因。');
  const next = structuredClone(record);
  next.status = '已取消';
  next.cancelledFromStatus = record.status as Exclude<ServiceRequest['status'], '已取消'>;
  next.updatedAt = now;
  next.operations?.assessment?.plans.forEach(plan => { if (!plan.releasedAt) plan.releasedAt = now; });
  next.operations?.assessment?.approvals.forEach(approval => {
    if (['待审批', '已通过'].includes(approval.state)) approval.state = '已失效';
  });
  return appendActivity(next, actor, '提交', activityMessage("取消服务请求"), reason.trim(), now);
}

// Check the cancellation against the current stored state, including actor and history.
export function requestCancellationSaveIssue(next: ServiceRequest, previous: ServiceRequest | undefined, actor: OperationActor | undefined, users: InternalUser[]): string | null {
  if (previous?.status === '已取消') return next.status === '已取消' ? null : '已取消的服务请求不能恢复，请新建请求。';
  if (next.status !== '已取消') return null;
  if (!previous || !actor) return '请由负责项目经理通过“取消服务请求”操作取消。';
  const event = next.operations?.activities.at(-1);
  if (!event?.id || !event.at || !Number.isFinite(Date.parse(event.at)) || !event.detail?.trim()) return '请填写取消原因并确认取消。';
  try {
    const expected = cancelRequest(previous, actor, users, event.detail, event.at);
    // The event ID is generated by the client; every business value must match.
    expected.operations!.activities.at(-1)!.id = event.id;
    expected.updatedAt = next.updatedAt;
    if (JSON.stringify(expected) !== JSON.stringify(next)) return '请求已变化或取消内容无效，请刷新后重新取消。';
    return null;
  } catch (issue) { return issue instanceof Error ? issue.message : '取消失败，请刷新后重试。'; }
}
