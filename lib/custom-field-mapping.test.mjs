import test from 'node:test';
import assert from 'node:assert/strict';
import { compatibleMappingFields, customFieldValueIssue, parseCustomFieldMappings, validateCustomFieldMappings, mappedCustomValues } from './custom-field-mapping.ts';
import { normalizeProjectFields } from './service-project-fields.ts';
import { newServiceProject, editServiceProject } from './service-projects.ts';
import { parseProjectMapping, defaultProjectMapping } from './request-project-mapping.ts';
const field = (id, type = 'text', options = []) => ({ id, name: id, type, options: options.map(value => ({ value, enabled: true })) });
const source = field('req-custom'), target = field('project-custom');
const mapping = { source, target, readonly: true };
test('项目字段库保留新增字段，映射按编号识别且支持兼容类型和选项', () => {
  assert.ok(normalizeProjectFields([target]).some(value => value.id === target.id));
  assert.equal(compatibleMappingFields(field('a', 'text'), field('b', 'textarea')), true);
  assert.equal(compatibleMappingFields(field('a', 'integer'), field('b', 'decimal')), true);
  assert.equal(compatibleMappingFields(field('a', 'decimal'), field('b', 'integer')), false);
  assert.equal(compatibleMappingFields(field('a', 'date'), field('b')), false);
  assert.equal(compatibleMappingFields(field('a', 'multiple', ['A', 'B']), field('b', 'multiple', ['A'])), false);
  assert.equal(compatibleMappingFields(field('a', 'multiple', ['A']), field('b', 'multiple', ['A', 'B'])), true);
  assert.equal(compatibleMappingFields({ ...field('a', 'lookup'), referenceTarget: 'users' }, { ...field('b', 'lookup'), referenceTarget: 'customers' }), false);
});
test('映射拒绝损坏、重复目标、系统字段篡改及已删除或类型改变的字段', () => {
  assert.throws(() => parseCustomFieldMappings([null]), /无效/);
  assert.throws(() => parseCustomFieldMappings([mapping, mapping]), /重复/);
  assert.throws(() => parseCustomFieldMappings([{ ...mapping, target: field('name') }]), /目标无效/);
  assert.throws(() => parseCustomFieldMappings([{ ...mapping, readonly: 'true' }]), /无效/);
  const config = { ...defaultProjectMapping(), customFields: [mapping] };
  assert.deepEqual(parseProjectMapping(config).customFields, [mapping]);
  assert.throws(() => validateCustomFieldMappings([mapping], {}), /定义已变化/);
  assert.throws(() => validateCustomFieldMappings([mapping], { applicationFields: [source], projectFields: [{ ...target, type: 'date' }] }), /定义已变化/);
  assert.doesNotThrow(() => validateCustomFieldMappings([mapping], { applicationFields: [{ ...source, name: '重命名' }], projectFields: [target] }));
});
test('转换复制自定义字段、内置来源和空值，并校验日期、数字、选项的实际值', () => {
  assert.deepEqual(mappedCustomValues({ customValues: { [source.id]: '原始内容' } }, [mapping]), { [target.id]: '原始内容' });
  assert.deepEqual(mappedCustomValues({}, [mapping]), { [target.id]: '' });
  assert.deepEqual(mappedCustomValues({ title: '申请主题' }, [{ ...mapping, source: field('title') }]), { [target.id]: '申请主题' });
  for (const [type, value] of [['integer', '1.5'], ['decimal', 'Infinity'], ['date', '2026-02-30'], ['single', 'B'], ['multiple', '["B"]']]) assert.ok(customFieldValueIssue(field('值', type, ['A']), value));
  assert.equal(customFieldValueIssue(field('日期', 'date'), '2026-09-16'), null);
  const choice = { source: field('s', 'single', ['A']), target: field('t', 'single', ['A']), readonly: false };
  assert.throws(() => mappedCustomValues({ customValues: { s: '失效选项' } }, [choice]), /选项不符/);
});
test('项目自定义字段独立保存，只读快照拦截修改与清空，未传入值时保留原值', () => {
  const actor = { id: 'pm', name: '经理', role: 'SmartX 项目经理' };
  const customers = [{ id: 'c', name: '客户', status: '启用' }];
  const input = { name: '项目', expectedServiceDate: '2026-09-20', customerId: 'c', note: '', customValues: { [target.id]: '原始内容', editable: '旧值' } };
  const project = newServiceProject(input, actor, customers);
  project.requestConversion = { mapping: { ...defaultProjectMapping(), customFields: [mapping] }, workOrders: [] };
  input.customValues[target.id] = '修改外部数据';
  assert.equal(project.customValues[target.id], '原始内容');
  const edit = { ...project, customValues: { ...project.customValues, editable: '新值' } };
  assert.equal(editServiceProject(project, edit, actor, customers).customValues.editable, '新值');
  assert.throws(() => editServiceProject(project, { ...edit, customValues: {} }, actor, customers), /只读/);
  assert.throws(() => editServiceProject(project, { ...edit, customValues: { [target.id]: '修改' } }, actor, customers), /只读/);
  assert.deepEqual(editServiceProject(project, { ...edit, customValues: undefined }, actor, customers).customValues, project.customValues);
});
